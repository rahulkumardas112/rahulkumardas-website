-- Students Hub catalogue. The live table was created in the connected Supabase project.
-- Keep this file as the project schema reference.
create table if not exists public.study_materials (
 id bigint generated by default as identity primary key,
 title text not null,
 description text not null default '',
 resource_type text not null check (resource_type in ('notes','solved_paper','question_paper','syllabus','bundle')),
 university text not null default '',
 course text not null default '',
 semester text not null default '',
 subject text not null default '',
 academic_level text not null default '',
 exam_year text not null default '',
 price numeric(10,2) not null default 0 check (price >= 0),
 access_type text not null default 'free' check (access_type in ('free','paid')),
 file_url text not null default '',
 preview_url text not null default '',
 published boolean not null default false,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.study_materials enable row level security;
create policy "Public can view published study materials" on public.study_materials for select to anon, authenticated using (published = true);
create policy "Admins manage study materials" on public.study_materials for all to authenticated using (exists (select 1 from public.admin_users a where a.id = (select auth.uid()))) with check (exists (select 1 from public.admin_users a where a.id = (select auth.uid())));
grant select on public.study_materials to anon, authenticated;
grant insert, update, delete on public.study_materials to authenticated;
grant usage, select on sequence public.study_materials_id_seq to authenticated;
